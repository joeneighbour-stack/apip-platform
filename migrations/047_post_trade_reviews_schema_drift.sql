-- 1. Fix alignment_score constraint (0-2 → 0-4)
alter table post_trade_reviews
  drop constraint if exists post_trade_reviews_alignment_score_check;

alter table post_trade_reviews
  add constraint post_trade_reviews_alignment_score_check
  check (alignment_score between 0 and 4);

-- 2. Add stop_alignment
alter table post_trade_reviews
  add column if not exists stop_alignment text
  check (stop_alignment in ('High', 'Low', 'Unknown'));

-- 3. Add target_alignment
alter table post_trade_reviews
  add column if not exists target_alignment text
  check (target_alignment in ('High', 'Low', 'Unknown'));

-- 4. Add review_status
alter table post_trade_reviews
  add column if not exists review_status text not null default 'PENDING'
  check (review_status in ('PENDING', 'GENERATED', 'ACKNOWLEDGED', 'MANAGER_REVIEWED', 'CLOSED'));

-- Update comment to reflect 0-4 scoring
comment on column post_trade_reviews.alignment_score is
  'Sum of direction (1) + entry (1) + stop (1) + target (1) alignment scores. Range 0-4.';

comment on column post_trade_reviews.stop_alignment is
  'Stop placement alignment: High if within suggested risk range (±0.5 ATR20), Low otherwise.';

comment on column post_trade_reviews.target_alignment is
  'Target placement alignment: High if within suggested target range (±0.5 ATR20), Low otherwise.';

comment on column post_trade_reviews.review_status is
  'Lifecycle status of this review. GENERATED by engine, ACKNOWLEDGED by analyst, MANAGER_REVIEWED/CLOSED by manager.';
