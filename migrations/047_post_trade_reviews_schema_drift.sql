-- Reconciles the live schema against 033_post_trade_reviews.sql.
-- Three changes were made out-of-band (via Supabase Studio or applied scripts)
-- between migration 033 and now -- confirmed live via PostgREST introspection
-- before writing this migration: stop_alignment, target_alignment and
-- review_status all already exist on the live table (033/034 already track
-- review_status's own addition; stop_alignment/target_alignment were not
-- tracked anywhere). alignment_score's column comment is still the original
-- "Range 0-2" text live, confirming it was never updated for the 0-4 scoring
-- generatePostTradeReviews.ts has been writing (confirmed live: alignment_score
-- values up to 4 already exist on this table, which a still-enforced 0-2 check
-- constraint would reject) -- this migration corrects the comment either way,
-- and the constraint rewrite converges it to 0-4 whether it was still 0-2,
-- already manually widened, or unconstrained.
--   1. alignment_score constraint was 0-2 (direction + entry only).
--      Extended to 0-4 when stop_alignment and target_alignment were added
--      (each contributing 1 point). Corrected here.
--   2. stop_alignment column added (nullable text, 'High' or 'Low').
--   3. target_alignment column added (nullable text, 'High' or 'Low').
--   4. review_status column added with default 'PENDING'.
-- RLS policies for this table are in 035_post_trade_reviews_rls.sql.
