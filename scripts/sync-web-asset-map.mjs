// ============================================================================
// Regenerates apps/web/lib/azureAssetMap.generated.ts from
// intelligence-engine/finnhub_to_acuity.csv (the single source of truth for
// price symbol -> Azure AssetId). The web app is deployed on its own, so it
// can't read the engine's CSV at runtime; it gets the venue-prefixed rows
// (OANDA:, BINANCE:, COINBASE:, FXCM:, ...) baked in instead. Stock rows are
// not used by any market and are left out.
//
// Run after any change to the CSV:
//   node scripts/sync-web-asset-map.mjs
// apps/web/lib/__tests__/azureAssetMap.test.ts fails if the two drift apart.
// ============================================================================
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const csvPath = path.join(root, 'intelligence-engine/finnhub_to_acuity.csv')
const outPath = path.join(root, 'apps/web/lib/azureAssetMap.generated.ts')

export function venueAssetMap(csvText) {
  const lines = csvText.split(/\r?\n/).filter(l => l.trim().length > 0)
  const header = lines[0].split(',').map(h => h.trim())
  const symbolIdx = header.indexOf('FinnhubSymbol')
  const assetIdIdx = header.indexOf('AssetId')
  const map = new Map()
  for (const line of lines.slice(1)) {
    const cols = line.split(',')
    const symbol = cols[symbolIdx]?.trim()
    const assetId = cols[assetIdIdx]?.trim()
    if (!symbol || !assetId || !symbol.includes(':')) continue
    // Same rule as intelligence-engine/src/lib/azurePrices.ts: first occurrence wins.
    if (!map.has(symbol)) map.set(symbol, assetId)
  }
  return map
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const map = venueAssetMap(readFileSync(csvPath, 'utf8'))
  const body = [...map].sort(([a], [b]) => a.localeCompare(b))
    .map(([symbol, assetId]) => `  ${JSON.stringify(symbol)}: ${JSON.stringify(assetId)},`).join('\n')
  writeFileSync(outPath,
`// GENERATED by scripts/sync-web-asset-map.mjs from
// intelligence-engine/finnhub_to_acuity.csv -- do not edit by hand.
// Price symbol (markets.price_data_symbol) -> Azure Table Storage AssetId.
export const AZURE_ASSET_IDS: Record<string, string> = {
${body}
}
`)
  console.log(`Wrote ${map.size} entries to ${path.relative(root, outPath)}`)
}
